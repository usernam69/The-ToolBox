// Writes STORAGE.md: every localStorage key the ToolBox uses and which file owns it.
// Run: node tests/keys.js        (CI runs it with --check and fails if STORAGE.md is out of date)
const fs = require('fs'), path = require('path');
const ROOT = process.env.TOOLBOX_DIR || path.join(__dirname, '..', 'toolbox'), OUT = path.join(__dirname, '..', 'STORAGE.md');
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? (e.name === 'vendor' ? [] : walk(path.join(d, e.name))) : [path.join(d, e.name)]);
const rows = new Map();
const add = (key, file, how) => { const k = key + '|' + file; if (!rows.has(k)) rows.set(k, { key, file, how }); };
for (const f of walk(ROOT).filter(f => /\.(js|html)$/.test(f))) {
  const src = fs.readFileSync(f, 'utf8'), rel = path.relative(ROOT, f).split(path.sep).join('/');
  const app = (src.match(/data-app="([\w-]+)"/) || [])[1];
  // the Toolbox (js/*.js) saves under tb_, each app under app_<id>_, shared helpers under tb_
  const prefix = rel.startsWith('js/') ? 'tb_' : app ? `app_${app}_` : null;
  if (prefix) for (const m of src.matchAll(/\bsave\('([\w-]+)'/g)) add(prefix + m[1], rel, 'save');
  for (const m of src.matchAll(/\bsaveTb\('([\w-]+)'/g)) add('tb_' + m[1], rel, 'saveTb');
  for (const m of src.matchAll(/localStorage\.setItem\(\s*'([\w-]+)'/g)) add(m[1], rel, 'direct');
  for (const m of src.matchAll(/(?:menuLS|REMIND)\.set\('([\w-]+)'/g)) add((/REMIND/.test(m[0]) ? 'tb_' : '') + m[1], rel, 'helper');
}
const list = [...rows.values()].sort((a, b) => a.key.localeCompare(b.key) || a.file.localeCompare(b.file));
const md = `# Where The ToolBox keeps data

Everything is in the browser's localStorage (or the desktop app's own folder). Generated by \`node tests/keys.js\`; don't edit by hand.

- \`tb_…\`: the Toolbox and settings shared by every app
- \`app_<id>_…\`: one app's own data
- \`menu_…\`: the main menu
- \`prof_…\`: saved family profiles

Keys built in code (like \`best\`+level) show their fixed start.

| Key | Written by |
|---|---|
${list.map(r => `| \`${r.key}\` | ${r.file} |`).join('\n')}
`;
if (process.argv.includes('--check')) {
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (old.replace(/\r/g, '') !== md) { console.error('✗ STORAGE.md is out of date. Run: node tests/keys.js'); process.exit(1); }
  console.log(`✓ STORAGE.md up to date (${list.length} keys)`);
} else { fs.writeFileSync(OUT, md); console.log(`STORAGE.md: ${list.length} keys`); }
